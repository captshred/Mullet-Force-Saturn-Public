#!/usr/bin/env python3
"""Pack Noah's original PNGs into double-buffered Saturn RGB555 sprite bands."""
import argparse
import hashlib
import json
import struct
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ACTORS = {
    "Buck": ((20, 23, 16), (23, 42, 80), (42, 61, 72), (61, 86, 56), (86, 100, 40), (100, 108, 24)),
    "Chuck": ((20, 24, 24), (24, 39, 80), (39, 52, 72), (52, 85, 64), (85, 101, 48), (101, 108, 24)),
}
ANCHOR = (64, 108)


def native(pixel):
    r, g, b, alpha = pixel
    assert alpha in (0, 255)
    return 0 if alpha == 0 else 0x8000 | (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)


def pack_frame(image, bands):
    packed = bytearray()
    starts = []
    for top, bottom, width in bands:
        box = image.crop((0, top, 128, bottom)).getbbox()
        left = box[0] if box else 0
        assert not box or box[2] - left <= width
        starts.append(left)
        strip = image.crop((left, top, left + width, bottom))
        pixels = [native(p) for p in strip.getdata()]
        packed.extend(struct.pack(f">{len(pixels)}H", *pixels))
        packed.extend(bytes(-len(packed) % 32))
    return bytes(packed), starts


def verify(frame, data, bands, starts):
    """Independently reconstruct the complete native canvas from upload data."""
    reconstructed = [0] * (128 * 128)
    offset = 0
    for (top, bottom, width), left in zip(bands, starts):
        count = width * (bottom - top)
        pixels = struct.unpack_from(f">{count}H", data, offset)
        for y in range(top, bottom):
            start = (y-top) * width
            begin = y * 128 + left
            reconstructed[begin:begin+width] = pixels[start:start+width]
        offset += (count * 2 + 31) // 32 * 32
    assert offset == len(data)
    assert reconstructed == [native(p) for p in frame.getdata()]
    return reconstructed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("artist_source", type=Path)
    parser.add_argument("--review", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    out = ROOT / "assets/noah-run"
    out.mkdir(exist_ok=True)
    outputs = {}
    actors = []
    max_frame_bytes = texture_bytes = 0
    for actor, bands in ACTORS.items():
        frames = []
        for index in range(1, 5):
            name = f"{actor}_RUN_{index:02}.png"
            raw = (args.artist_source / actor / name).read_bytes()
            frame = Image.open(args.artist_source / actor / name).convert("RGBA")
            assert frame.size == (128, 128) and frame.getbbox()[3] == ANCHOR[1]
            data, starts = pack_frame(frame, bands)
            reconstructed = verify(frame, data, bands, starts)
            filename = f"N{actor[0]}{index:02}.BIN"
            outputs[out / filename] = data
            frames.append(dict(source=name, source_sha256=hashlib.sha256(raw).hexdigest(),
                               file=filename, left=starts, sha256=hashlib.sha256(data).hexdigest()))
            if args.review:
                args.review.mkdir(parents=True, exist_ok=True)
                review = Image.new("RGBA", frame.size)
                review.putdata([tuple(((n >> shift) & 31) * 255 // 31 for shift in (0, 5, 10))+(255,)
                                if n else (0, 0, 0, 0) for n in reconstructed])
                review.save(args.review / name)
        actors.append(dict(name=actor, bands=bands, frames=frames, bytes_per_frame=len(data)))
        texture_bytes += 2 * len(data)
        max_frame_bytes = max(max_frame_bytes, len(data))
    manifest = dict(canvas=[128, 128], root=ANCHOR, frame_ticks=6, native_format="RGB555 big-endian",
                    texture_bytes=texture_bytes, sprite_slots=24,
                    source_cache_bytes=sum(a["bytes_per_frame"] * 4 for a in actors), actors=actors)
    outputs[out / "manifest.json"] = (json.dumps(manifest, indent=2) + "\n").encode()
    header = ["/* Generated by tools/pack-noah-run.py. */",
              f"#define MF_NOAH_RUN_BYTES {texture_bytes}u",
              f"#define MF_NOAH_FRAME_MAX {max_frame_bytes}u",
              f"#define MF_NOAH_BUCK_BYTES {actors[0]['bytes_per_frame']}u",
              f"#define MF_NOAH_CHUCK_BYTES {actors[1]['bytes_per_frame']}u",
              "enum { MF_NOAH_PARTS = 6, MF_NOAH_ROOT_X = 64, MF_NOAH_ROOT_Y = 108 };",
              "static const struct { unsigned short y, width, height; } noah_bands[2][MF_NOAH_PARTS] = {"]
    for actor in actors:
        header.append("    {" + ", ".join(f"{{{y}, {w}, {bottom-y}}}" for y, bottom, w in actor["bands"]) + "},")
    header += ["};", "static const struct { const char *name; unsigned char x[MF_NOAH_PARTS]; } noah_frames[2][4] = {"]
    for actor in actors:
        header.append("    {")
        for f in actor["frames"]:
            header.append('        {"' + f["file"] + '", {' + ", ".join(map(str, f["left"])) + "}},")
        header.append("    },")
    header.append("};")
    outputs[ROOT / "src/noah_run_data.h"] = ("\n".join(header) + "\n").encode()
    for path, data in outputs.items():
        if args.check:
            assert path.read_bytes() == data, path
        else:
            path.write_bytes(data)
    print(f"8 frames verified against source at RGB555 precision, {texture_bytes} VDP1 bytes, "
          f"{manifest['source_cache_bytes']} source cache bytes")


if __name__ == "__main__":
    main()
